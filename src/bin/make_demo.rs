//! Original, redistributable fixture so a fresh checkout needs no game artwork.
#[cfg(not(target_arch = "wasm32"))]
fn main() -> anyhow::Result<()> {
    use image::{Rgba, RgbaImage};
    use sprite_lab::format::Package;
    use std::{collections::BTreeMap, io::Cursor};
    let mut entries = BTreeMap::new();
    for part in ["body", "arm", "orb"] {
        let mut color = RgbaImage::new(48, 48);
        let mut normal = color.clone();
        let mut surface = color.clone();
        let mut emission = color.clone();
        for y in 0..48 {
            for x in 0..48 {
                let dx = (x as f32 - 23.5) / 21.0;
                let dy = (y as f32 - 23.5) / 21.0;
                let r = (dx * dx + dy * dy).sqrt();
                let inside = if part == "arm" {
                    x > 17 && x < 30 && y > 7 && y < 42
                } else {
                    r < 1.0
                };
                if !inside {
                    continue;
                }
                let mut c = if part == "orb" {
                    [100, 230, 250, 255]
                } else if part == "arm" {
                    [231, 154, 65, 255]
                } else {
                    [82, 149, 158, 255]
                };
                if part == "body" && y > 18 && y < 26 && ((x > 12 && x < 18) || (x > 29 && x < 35))
                {
                    c = [240, 237, 179, 255];
                    emission.put_pixel(x, y, Rgba([205, 235, 110, 255]));
                }
                if part == "orb" {
                    emission.put_pixel(x, y, Rgba([25, 90, 100, 255]));
                }
                color.put_pixel(x, y, Rgba(c));
                let nx = dx * 0.65;
                let ny = -dy * 0.65;
                let nz = (1.0 - nx * nx - ny * ny).max(0.01).sqrt();
                normal.put_pixel(
                    x,
                    y,
                    Rgba([
                        ((nx * 0.5 + 0.5) * 255.0) as u8,
                        ((ny * 0.5 + 0.5) * 255.0) as u8,
                        ((nz * 0.5 + 0.5) * 255.0) as u8,
                        255,
                    ]),
                );
                surface.put_pixel(
                    x,
                    y,
                    Rgba([255, 255, if part == "orb" { 255 } else { 0 }, 255]),
                );
            }
        }
        for (name, map) in [
            ("color", color),
            ("normal", normal),
            ("surface", surface),
            ("emission", emission),
        ] {
            let mut bytes = Cursor::new(Vec::new());
            image::DynamicImage::ImageRgba8(map)
                .write_to(&mut bytes, image::ImageOutputFormat::Png)?;
            entries.insert(format!("{part}-{name}.png"), bytes.into_inner());
        }
    }
    let key =
        |tick: f32, value: f32| serde_json::json!({"tick":tick,"value":value,"ease":"easeInOut"});
    let track = |part: &str, image: &str, x: f32, y: f32, z: f32| serde_json::json!({"part":part,"image":[{"tick":0,"value":image}],"x":[key(0.0,x)],"y":[key(0.0,y)],"z":[key(0.0,z)]});
    let mut arm = track("arm", "arm", 20.0, -5.0, 0.0);
    arm["rotation"] = serde_json::json!([key(0.0, -25.0), key(60.0, 35.0), key(120.0, -25.0)]);
    let mut orb = track("orb", "orb", 38.0, -25.0, 2.0);
    orb["emission"] = serde_json::json!([key(0.0, 0.3), key(60.0, 2.0), key(120.0, 0.3)]);
    let images=["body","arm","orb"].iter().map(|part|serde_json::json!({"id":part,"name":part,"x":-24,"y":-24,"color":format!("{part}-color.png"),"normal":format!("{part}-normal.png"),"surface":format!("{part}-surface.png"),"emission":format!("{part}-emission.png"),"material":if *part=="orb"{"glass"}else{"shell"}})).collect::<Vec<_>>();
    let doc = serde_json::json!({"format":"sprite-lab","version":0,"name":"Copperbot","ticksPerSecond":60,"required":["core-0"],
        "materials":[{"id":"shell","name":"Brushed copper","roughness":0.5,"metalness":0.7,"emission":1.5},
            {"id":"glass","name":"Luminous glass","roughness":0.12,"transmission":0.7,"emission":2.0}],
        "views":[{"id":"front","name":"Front","canvas":{"x":-40,"y":-54,"width":108,"height":100},
            "parts":[{"id":"body","name":"Body"},{"id":"arm","name":"Arm","parent":"body"},{"id":"orb","name":"Glass orb","parent":"arm"}],
            "images":images,
            "animations":[{"id":"idle","name":"Orbit","length":120,"looping":true,"tracks":[track("body","body",0.0,5.0,1.0),arm,orb]}]}],
        "extras":{"provenance":"Original procedural test artwork generated by make-demo; freely reusable."}});
    let package = Package {
        document: serde_json::from_value(doc)?,
        entries,
        compressed_bytes: 0,
        migrated_from: None,
    };
    package.document.validate()?;
    std::fs::create_dir_all("web/examples")?;
    std::fs::write("web/examples/copperbot.sprite", package.write()?)?;
    println!("Wrote web/examples/copperbot.sprite");
    Ok(())
}
#[cfg(target_arch = "wasm32")]
fn main() {}
